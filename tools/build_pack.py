#!/usr/bin/env python3
"""Packs the game's local 3D models and textures into assets/pack/*.js so stormfall.html also runs
when it is opened by double-clicking it (Chrome blocks file:// reads, but allows local <script> files).
Run this again after adding or changing anything in assets/models or assets/textures:  python3 tools/build_pack.py"""
import base64, glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
PACKS = {
    'models': sorted(glob.glob('assets/models/s2/*.glb')) + sorted(glob.glob('assets/models/pets/*.glb'))
              + ['assets/models/Xbot.glb'],
    'chars': sorted(glob.glob('assets/models/chars/*.glb')),
    'textures': sorted(f for f in glob.glob('assets/textures/s2/*.jpg') if not f.endswith('_ao.jpg')),
}
os.makedirs('assets/pack', exist_ok=True)
for name, files in PACKS.items():
    data = {f: base64.b64encode(open(f, 'rb').read()).decode('ascii') for f in files if os.path.exists(f)}
    out = f'assets/pack/{name}.js'
    with open(out, 'w') as fh:
        fh.write('/* generated by tools/build_pack.py: local assets for opening stormfall.html straight from disk */\n')
        fh.write('window.SF_PACK=window.SF_PACK||{};Object.assign(window.SF_PACK,' + json.dumps(data, separators=(',', ':')) + ');\n')
    print(f'{out}: {len(data)} files, {os.path.getsize(out) / 1e6:.1f} MB')
